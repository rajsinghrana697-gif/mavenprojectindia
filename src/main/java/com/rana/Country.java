package com.rana;

public class Country {
    public String delhi;
    public String jammu;
    public String punjab;

    public String getDelhi() {
        return delhi;
    }

    public void setDelhi(String delhi) {
        this.delhi = delhi;
    }

    public String getJammu() {
        return jammu;
    }

    public void setJammu(String jammu) {
        this.jammu = jammu;
    }

    public String getPunjab() {
        return punjab;
    }

    public void setPunjab(String punjab) {
        this.punjab = punjab;
    }
}
